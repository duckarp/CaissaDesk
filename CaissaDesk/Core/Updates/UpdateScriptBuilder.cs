using System.Globalization;
using System.Text;

namespace CaissaDesk.Core.Updates;

/// <summary>Inputs of the helper script that swaps the executable after the app has exited.</summary>
public sealed record UpdateScriptPlan(
    int ProcessId,
    string NewExecutable,
    string TargetExecutable,
    string StagingDirectory,
    string LogFile)
{
    public string AppDirectory => Path.GetDirectoryName(TargetExecutable)
                                  ?? throw new InvalidOperationException("The target executable has no directory.");
    public string BackupExecutable => TargetExecutable + ".bak";
    public string TemporaryExecutable => TargetExecutable + ".new";
}

/// <param name="Environment">Variables the launcher must set for the script (Windows passes all paths this way).</param>
public sealed record UpdateScript(string FileName, string Content, IReadOnlyDictionary<string, string> Environment);

/// <summary>
/// Generates the helper script. It waits for the app's PID to exit (bounded), copies the staged executable
/// next to the old one, swaps them with renames inside the install directory (keeping "&lt;exe&gt;.bak" and
/// rolling back if the swap fails), restarts the app and removes the staging folder including itself.
/// It never extracts archives: extraction and verification already happened in .NET.
/// </summary>
public static class UpdateScriptBuilder
{
    /// <summary>How long the script waits for the app to exit before giving up (seconds).</summary>
    public const int WaitSeconds = 120;

    public const string EnvPrefix = "CAISSADESK_UPDATE_";

    /// <summary>POSIX sh script; every path is embedded as a single-quoted literal (no expansion of $, `, \ or ").</summary>
    public static UpdateScript BuildShellScript(UpdateScriptPlan plan)
    {
        Validate(plan);
        var sb = new StringBuilder();
        sb.Append("#!/bin/sh\n");
        sb.Append("# Generated by CaissaDesk: applies a downloaded update after the app exits, then restarts it.\n");
        sb.Append("set -u\n");
        sb.Append("PID=").Append(plan.ProcessId.ToString(CultureInfo.InvariantCulture)).Append('\n');
        sb.Append("NEW=").Append(ShellQuote(plan.NewExecutable)).Append('\n');
        sb.Append("TARGET=").Append(ShellQuote(plan.TargetExecutable)).Append('\n');
        sb.Append("BACKUP=").Append(ShellQuote(plan.BackupExecutable)).Append('\n');
        sb.Append("TMP=").Append(ShellQuote(plan.TemporaryExecutable)).Append('\n');
        sb.Append("APPDIR=").Append(ShellQuote(plan.AppDirectory)).Append('\n');
        sb.Append("STAGING=").Append(ShellQuote(plan.StagingDirectory)).Append('\n');
        sb.Append("LOG=").Append(ShellQuote(plan.LogFile)).Append('\n');
        sb.Append("WAIT=").Append(WaitSeconds.ToString(CultureInfo.InvariantCulture)).Append('\n');
        sb.Append("""
            exec >>"$LOG" 2>&1
            echo "$(date '+%Y-%m-%d %H:%M:%S') update: waiting for process $PID"

            restart() {
                cd "$APPDIR" || cd /
                nohup "$TARGET" >/dev/null 2>&1 &
            }

            # A zombie (exited, not yet reaped by its parent) still answers kill -0: treat it as exited
            running() {
                kill -0 "$PID" 2>/dev/null || return 1
                if [ -r "/proc/$PID/stat" ]; then
                    state=$(sed 's/^.*) //' "/proc/$PID/stat" 2>/dev/null | cut -c1)
                    [ "$state" = "Z" ] && return 1
                fi
                return 0
            }

            i=0
            while running; do
                i=$((i + 1))
                if [ "$i" -ge "$WAIT" ]; then
                    echo "update: process $PID did not exit, update not applied"
                    exit 1
                fi
                sleep 1
            done

            if ! cp -f "$NEW" "$TMP" || ! chmod 755 "$TMP"; then
                echo "update: could not copy the new executable next to the old one"
                rm -f "$TMP"
                restart
                exit 1
            fi

            rm -f "$BACKUP"
            if ! mv -f "$TARGET" "$BACKUP"; then
                echo "update: could not back up the current executable"
                rm -f "$TMP"
                restart
                exit 1
            fi

            if ! mv -f "$TMP" "$TARGET"; then
                echo "update: could not install the new executable, restoring the previous one"
                mv -f "$BACKUP" "$TARGET"
                rm -f "$TMP"
                restart
                exit 1
            fi

            echo "update: installed, restarting"
            restart
            rm -rf -- "$STAGING"
            exit 0

            """.Replace("\r\n", "\n"));
        return new UpdateScript("apply-update.sh", sb.ToString(), new Dictionary<string, string>());
    }

    /// <summary>
    /// Windows batch script. cmd.exe re-expands %...% inside literals and reads batch files in the OEM code
    /// page, so no path is embedded: all of them arrive as environment variables set by the launcher and
    /// are only ever used inside double quotes ("%VAR%" expands once; " cannot occur in Windows paths;
    /// delayed expansion is disabled so ! stays literal).
    /// </summary>
    public static UpdateScript BuildWindowsScript(UpdateScriptPlan plan)
    {
        Validate(plan);
        foreach (string path in Paths(plan))
        {
            if (path.Contains('"')) throw new ArgumentException($"Path contains a double quote: {path}", nameof(plan));
        }

        var env = new Dictionary<string, string>(StringComparer.Ordinal)
        {
            [EnvPrefix + "PID"] = plan.ProcessId.ToString(CultureInfo.InvariantCulture),
            [EnvPrefix + "NEW"] = plan.NewExecutable,
            [EnvPrefix + "TARGET"] = plan.TargetExecutable,
            [EnvPrefix + "BACKUP"] = plan.BackupExecutable,
            [EnvPrefix + "TMP"] = plan.TemporaryExecutable,
            [EnvPrefix + "APPDIR"] = plan.AppDirectory,
            [EnvPrefix + "STAGING"] = plan.StagingDirectory,
            [EnvPrefix + "LOG"] = plan.LogFile
        };

        string content = $"""
            @echo off
            rem Generated by CaissaDesk: applies a downloaded update after the app exits, then restarts it.
            rem All paths come from {EnvPrefix}* environment variables set by CaissaDesk.
            setlocal EnableExtensions DisableDelayedExpansion
            if not defined {EnvPrefix}TARGET exit /b 1
            set /a WAITED=0
            >>"%{EnvPrefix}LOG%" echo update: waiting for process %{EnvPrefix}PID%

            :wait
            tasklist /FI "PID eq %{EnvPrefix}PID%" /NH 2>nul | findstr /C:" %{EnvPrefix}PID% " >nul
            if errorlevel 1 goto exited
            set /a WAITED+=1
            if %WAITED% GEQ {WaitSeconds} goto timeout
            ping -n 2 127.0.0.1 >nul
            goto wait

            :timeout
            >>"%{EnvPrefix}LOG%" echo update: process did not exit, update not applied
            exit /b 1

            :exited
            copy /b /y "%{EnvPrefix}NEW%" "%{EnvPrefix}TMP%" >nul
            if errorlevel 1 goto copyfailed

            rem The executable can stay locked for a moment after exit (antivirus scans): retry the backup rename
            set /a TRIES=0
            :backup
            if exist "%{EnvPrefix}BACKUP%" del /f /q "%{EnvPrefix}BACKUP%" >nul 2>&1
            move /y "%{EnvPrefix}TARGET%" "%{EnvPrefix}BACKUP%" >nul 2>&1
            if not errorlevel 1 goto install
            set /a TRIES+=1
            if %TRIES% GEQ 10 goto backupfailed
            ping -n 2 127.0.0.1 >nul
            goto backup

            :install
            move /y "%{EnvPrefix}TMP%" "%{EnvPrefix}TARGET%" >nul 2>&1
            if errorlevel 1 goto rollback
            >>"%{EnvPrefix}LOG%" echo update: installed, restarting
            start "" /D "%{EnvPrefix}APPDIR%" "%{EnvPrefix}TARGET%"
            rem Leave the batch context before deleting the folder that contains this script
            (goto) 2>nul & rmdir /s /q "%{EnvPrefix}STAGING%"
            exit /b 0

            :rollback
            >>"%{EnvPrefix}LOG%" echo update: could not install the new executable, restoring the previous one
            move /y "%{EnvPrefix}BACKUP%" "%{EnvPrefix}TARGET%" >nul 2>&1
            goto restartold

            :backupfailed
            >>"%{EnvPrefix}LOG%" echo update: could not back up the current executable
            goto restartold

            :copyfailed
            >>"%{EnvPrefix}LOG%" echo update: could not copy the new executable next to the old one

            :restartold
            if exist "%{EnvPrefix}TMP%" del /f /q "%{EnvPrefix}TMP%" >nul 2>&1
            start "" /D "%{EnvPrefix}APPDIR%" "%{EnvPrefix}TARGET%"
            exit /b 1

            """;
        return new UpdateScript("apply-update.cmd", content.Replace("\r\n", "\n").Replace("\n", "\r\n"), env);
    }

    /// <summary>Single-quotes a value for POSIX sh: ' becomes '\'' and nothing inside is expanded.</summary>
    public static string ShellQuote(string value) => "'" + value.Replace("'", "'\\''") + "'";

    private static IEnumerable<string> Paths(UpdateScriptPlan plan) =>
        [plan.NewExecutable, plan.TargetExecutable, plan.StagingDirectory, plan.LogFile];

    private static void Validate(UpdateScriptPlan plan)
    {
        if (plan.ProcessId <= 0) throw new ArgumentException("Invalid process id.", nameof(plan));
        foreach (string path in Paths(plan))
        {
            if (string.IsNullOrWhiteSpace(path) || !Path.IsPathFullyQualified(path))
            {
                throw new ArgumentException($"Script paths must be absolute: '{path}'.", nameof(plan));
            }
            if (path.Any(char.IsControl))
            {
                throw new ArgumentException("Script paths must not contain control characters.", nameof(plan));
            }
        }
    }
}
